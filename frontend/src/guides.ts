export function explain(p: Plugin) { const d=descriptions[p.name.toLowerCase()]||[p.name,p.description];return [tr(d[0]),tr(d[1])]; }
export function pick(plugins: Plugin[], os: OS, names: string[]) { return names.map(name => plugins.find(p => p.os === (name === 'banners' ? 'generic' : os) && p.name.toLowerCase() === name && !p.description.includes('deprecated'))).filter((p): p is Plugin => !!p); }
export function steps(plugins: Plugin[], os: OS) {
    return [
        {id:'processes',title:tr('Процессы'),text:tr('Активные процессы и их идентификаторы.'),plugins:pick(plugins,os,['pslist'])},
        {id:'connections',title:tr('Сетевые соединения'),text:tr('Соединения и связанные с ними процессы.'),plugins:pick(plugins,os,os==='windows'?['netscan']:os==='linux'?['sockstat']:['netstat'])},
        {id:'commands',title:tr('Командные строки'),text:tr('Аргументы запуска процессов.'),plugins:pick(plugins,os,os==='linux'?['psaux']:['cmdline'])}
    ];
}

